  function fIconize(root){
    if(!root) return;
    const tw=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,null);
    const targets=[];
    let n;
    while((n=tw.nextNode())){
      const p=n.parentNode;
      if(!p||p.nodeName==='SCRIPT'||p.nodeName==='STYLE'||p.nodeName==='TEXTAREA') continue;
      if(p.closest&&p.closest('.ficon-skip')) continue;
      RE.lastIndex=0;
      if(RE.test(n.nodeValue)) targets.push(n);
    }
    for(const t of targets){
      const parent=t.parentNode; if(!parent) continue;
      const fs=parseFloat(getComputedStyle(parent).fontSize)||14;
      const sz=Math.round(fs*1.08);
      RE.lastIndex=0;
      const html=esc(t.nodeValue).replace(RE,m=>{
        const key=keys.find(k=>m.startsWith(k))||m.replace(/\uFE0F$/,'');
        return svgFor(EMOJI_MAP[key]||EMOJI_MAP[m.replace(/\uFE0F$/,'')],sz);
      });
      const span=document.createElement('span');
      span.className='ficonized';
      span.innerHTML=html;
      parent.replaceChild(span,t);
    }
  }

